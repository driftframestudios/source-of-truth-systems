import { test, expect } from '@playwright/test';

test('compact Cohort tools preserve the editing canvas, draft and saved-rule receiver', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Cohort Builder', exact: true }).click();
  const editor = page.getByRole('region', { name: 'Cohort rule editor', exact: true });
  const facets = page.getByRole('complementary', { name: 'Facet cards', exact: true });
  const compiled = page.getByRole('complementary', { name: 'Compiled cohort rule', exact: true });
  expect((await editor.boundingBox()).width).toBeGreaterThan(500);
  await expect(facets).toBeVisible();
  await expect(compiled).toBeHidden();
  await page.getByRole('textbox', { name: 'Rule name', exact: true }).fill('Compact cohort draft');
  await page.getByRole('button', { name: 'Rule & saved', exact: true }).click();
  await expect(compiled).toBeVisible();
  await expect(facets).toBeHidden();
  await expect(page.getByLabel('Current cohort counts', { exact: true })).toContainText('consent-held');
  await page.getByRole('button', { name: 'Add cards', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Rule name', exact: true })).toHaveValue('Compact cohort draft');
  await page.getByRole('button', { name: 'Save rule', exact: true }).click();
  await expect(compiled).toBeVisible();
  await expect(page.getByRole('button', { name: 'Open rule Compact cohort draft', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1512, height: 982 });
  await expect(facets).toBeVisible();
  await expect(compiled).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Cohort tools', exact: true })).toBeHidden();
  await page.setViewportSize({ width: 1024, height: 768 });
  await expect(compiled).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Rule name', exact: true })).toHaveValue('Compact cohort draft');
});

test('compact Artifact inspection preserves its proposal through resizing and returns to the selected card', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.goto('/');
  await page.getByRole('button', { name: /^Artifacts/ }).click();
  const card = page.locator('[data-record-id="arc01_pass1"]');
  expect((await card.boundingBox()).width).toBeGreaterThan(200);
  await card.click();
  const detail = page.getByRole('region', { name: 'Artifact details', exact: true });
  expect((await detail.boundingBox()).width).toBeGreaterThan(700);
  await expect(detail).toBeFocused();
  await expect(card).toBeHidden();
  await expect(detail.getByRole('heading', { name: 'Platform bootstrap', exact: true })).toBeVisible();
  await detail.getByRole('button', { name: 'Prepare revision', exact: true }).click();
  const title = detail.getByRole('textbox', { name: 'Proposal title', exact: true });
  await title.fill('Compact proposal draft');
  await page.setViewportSize({ width: 1512, height: 982 });
  await expect(card).toBeVisible();
  await expect(title).toHaveValue('Compact proposal draft');
  await page.setViewportSize({ width: 1024, height: 768 });
  await expect(title).toHaveValue('Compact proposal draft');
  await detail.getByRole('button', { name: 'Save proposal', exact: true }).click();
  await detail.getByRole('button', { name: 'Back to gallery', exact: true }).click();
  await expect(detail).toHaveCount(0);
  await expect(card).toBeVisible();
  await expect(card).toBeFocused();
  await expect(card).toContainText('Proposal: Compact proposal draft');
  await card.click();
  await expect(title).toHaveValue('Compact proposal draft');
  await expect(detail.getByText('Recorded acceptance checks', { exact: true })).toBeVisible();
});
