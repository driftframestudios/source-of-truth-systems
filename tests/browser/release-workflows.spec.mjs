import {test,expect} from '@playwright/test';

test('release records retain accepted targets, replacements and decisions with shared counts and recovery', async ({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/^Requirements/}).click();
  const initialCount = Number((await page.getByRole('button',{name:/^Requirements/}).textContent()).match(/\d+/)[0]);
  const row=page.locator('[data-record-id="PIPE-STAGE-001"]');
  const details=row.locator('..');
  await row.click();
  await details.getByRole('combobox',{name:'Target release for PIPE-STAGE-001'}).selectOption('arc_03');
  await details.getByRole('button',{name:'Defer',exact:true}).click();
  await expect(row).toContainText('Deferred');
  await expect(row).toContainText('Release 03');
  await expect(page.getByRole('button',{name:/^Requirements/})).toContainText(String(initialCount - 1));
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('navigation',{name:'Explore the showcase'})).toBeVisible();
  await page.setViewportSize({width:1512,height:982});
  await page.getByRole('button',{name:/^Requirements/}).click();
  await expect(row).toContainText('Release 03');
  const activeAfter=await page.getByRole('button',{name:/^Requirements/}).textContent();
  await page.getByRole('button',{name:'Profile',exact:true}).click();
  await page.getByRole('group',{name:'Workspace role'}).getByRole('button',{name:'Viewer',exact:true}).click();
  await page.getByRole('button',{name:/^Requirements/}).click();
  await row.click();
  await details.getByRole('button',{name:'Restore original',exact:true}).click();
  await expect(row).toContainText('Deferred');
  await expect(page.getByRole('button',{name:/^Requirements/})).toHaveText(activeAfter);
  await expect(details.getByRole('status')).toContainText('Viewer');
  await page.getByRole('button',{name:'Profile',exact:true}).click();
  await page.getByRole('group',{name:'Workspace role'}).getByRole('button',{name:'Release Lead',exact:true}).click();
  await page.getByRole('button',{name:/^Requirements/}).click();
  await row.click();
  await details.getByRole('combobox',{name:'Replacement for PIPE-STAGE-001'}).selectOption('BATCH-QUEUE-001');
  await details.getByRole('button',{name:'Supersede',exact:true}).click();
  await expect(row).toContainText('Superseded');
  await expect(details.getByText('Replaced by BATCH-QUEUE-001',{exact:true})).toBeVisible();
  await details.getByRole('button',{name:'Restore original',exact:true}).click();
  await expect(row).toContainText('Active');
  await expect(page.getByRole('button',{name:/^Requirements/})).toContainText(String(initialCount));
  await expect(details.getByRole('button',{name:'Restore original',exact:true})).toHaveCount(0);

  await page.getByRole('button',{name:/^Decisions/}).click();
  const decision=page.locator('[data-record-id="DEC-007"]');
  await decision.getByRole('button',{name:'Revisit',exact:true}).click();
  await expect(decision).toContainText('Revisited');
  await decision.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(decision.getByRole('button',{name:'Confirm',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:/^Requirements/}).click();
  await page.getByRole('button',{name:/^Decisions/}).click();
  await expect(decision).toContainText('Confirmed');
  await decision.getByRole('button',{name:'Revisit',exact:true}).click();
  await expect(decision).toContainText('Revisited');
  await decision.getByRole('button',{name:'Restore original',exact:true}).click();
  await expect(decision).toContainText('Confirmed');
  await page.locator('#initial-load').waitFor({state:'hidden'});
  await page.screenshot({path:'.visual-runs/release-decisions.png'});
});
